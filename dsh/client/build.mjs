/**
 * Client-bundle builder for dsh-mizar.
 *
 * DSH accepts exactly one artifact form for a plugin's browser half: a script
 * that calls `window.__ModuleLoader__.load({ id, factory })`, where `factory` is
 * a CommonJS module body evaluated at materialization time. There is no ESM
 * path, and DSH's own client build toolchain is not published as a package, so
 * this script reproduces that envelope around plain esbuild output.
 *
 * Three properties matter and are easy to get wrong:
 *
 *   - The module body must live *inside* the factory, not at the top level, so
 *     it runs when the shell materializes the bundle rather than when the
 *     script is parsed.
 *   - `id` must be the exact package name; the boot graph matches on it.
 *   - The nine baseline modules are supplied by the shell and must stay
 *     external. Bundling a second copy of React breaks hooks.
 *
 * @module dsh-mizar/build-client
 */
import { build, context } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packageRoot = resolve(here, '..')

/**
 * Modules the shell's module loader already owns.
 *
 * Taken from the frozen `PLATFORM_MODULES` table in the built shell. Anything
 * listed here must not be bundled; anything *not* listed here that we import
 * would need a `dsh.client.external` declaration instead.
 */
const BASELINE_MODULES = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

const entry = resolve(here, 'src/index.tsx')
const outfile = resolve(packageRoot, 'lib/client.js')

/** Read the package name, which is also the bundle id the boot graph matches. */
async function readPackageId() {
  const raw = await readFile(resolve(packageRoot, 'package.json'), 'utf8')
  const manifest = JSON.parse(raw)
  if (typeof manifest.name !== 'string' || manifest.name === '') {
    throw new Error('build-client: package.json has no name')
  }
  return manifest.name
}

/** Indent a module body so the emitted envelope stays readable. */
function indent(text, pad = '      ') {
  return text
    .split('\n')
    .map((line) => (line.length === 0 ? line : pad + line))
    .join('\n')
}

/**
 * Wrap a CommonJS module body in the loader envelope.
 * @param id - the package name the boot graph addresses this bundle by.
 * @param body - esbuild's CommonJS output.
 * @returns the script the host serves at `/plugins/<id>/client.js`.
 */
function envelope(id, body) {
  return `// Generated by client/build.mjs — do not edit. Envelope required by
// dsh-client-modules; see the DSH-Mizar README for why this is hand-rolled.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(id)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${indent(body)}
    return module.exports;
  },
});
`
}

/** Run one esbuild pass and emit the wrapped artifact. */
async function buildOnce(id) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    jsx: 'automatic',
    external: BASELINE_MODULES,
    legalComments: 'none',
    logLevel: 'warning',
  })

  const body = result.outputFiles?.[0]?.text
  if (body === undefined) throw new Error('build-client: esbuild produced no output')

  await mkdir(dirname(outfile), { recursive: true })
  await writeFile(outfile, envelope(id, body), 'utf8')

  const bytes = Buffer.byteLength(body, 'utf8')
  console.log(`build-client: wrote ${outfile} (${bytes} B body)`)
}

/** Rebuild on change for development. */
async function watch(id) {
  const ctx = await context({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    jsx: 'automatic',
    external: BASELINE_MODULES,
    legalComments: 'none',
    logLevel: 'warning',
    plugins: [
      {
        name: 'mizar-envelope',
        setup(pluginBuild) {
          pluginBuild.onEnd(async (result) => {
            const body = result.outputFiles?.[0]?.text
            if (body === undefined) return
            await mkdir(dirname(outfile), { recursive: true })
            await writeFile(outfile, envelope(id, body), 'utf8')
            console.log(`build-client: rebuilt ${outfile}`)
          })
        },
      },
    ],
  })
  await ctx.watch()
  console.log('build-client: watching for changes')
}

const id = await readPackageId()
if (process.argv.includes('--watch')) await watch(id)
else await buildOnce(id)
